# ============ 二、派生计算 ============
def ring_length(p):
    return sum(s[1] for s in LOOP[p])


def ring_limit(p):
    """环闭合差限差 ±4√F (mm), F 为环长(km)"""
    return 4.0 * math.sqrt(ring_length(p) / 1000.0)


def benchmark_heights(p):
    """由 A 起算 B、C 高程"""
    b = H_A + LOOP[p][0][4] / M
    c = b + LOOP[p][1][4] / M
    return H_A, b, c


BENCH = {p: benchmark_heights(p) for p in (1, 2, 3)}


def mon_settle():
    """分期变化、累计沉降 (mm)"""
    out = {}
    for k, hs in MON.items():
        d1 = (hs[1] - hs[0]) * M
        d2 = (hs[2] - hs[1]) * M
        cum = (hs[2] - hs[0]) * M
        out[k] = dict(h1=hs[0], h2=hs[1], h3=hs[2], d1=d1, d2=d2, cum=cum,
                      rate=cum / 14.0)
    return out


SETTLE = mon_settle()


def bench_stability():
    """基准点稳定性: 各边两期高差较差 vs 限差"""
    rows = []
    for i, name in enumerate(["A → B", "B → C", "C → A"]):
        # 用改正后高差之差(等价于基准点高程变化), 因 A 固定
        d12 = LOOP[2][i][4] - LOOP[1][i][4]
        d23 = LOOP[3][i][4] - LOOP[2][i][4]
        d13 = LOOP[3][i][4] - LOOP[1][i][4]
        L = (LOOP[1][i][1] + LOOP[2][i][1] + LOOP[3][i][1]) / 3.0
        # 每公里高差中数中误差 μ=2 mm/√km(由 4√F 限差反算), 较差限差 2√2·μ√L
        lim = 2 * math.sqrt(2) * 2.0 * math.sqrt(L / 1000.0)
        rows.append(dict(name=name, L=L, d12=d12, d23=d23, d13=d13, lim=lim))
    return rows


STAB = bench_stability()


