# ==================== 二、全站仪面积测量 ====================
H1("二、普通全站仪面积测量")

H2("（一）任务与场地")
P("利用普通全站仪测量土力院一楼花圃（或停车场）的面积。采用任意架站、"
  "假定坐标的方式：测站可设在通视良好的空地，棱镜杆立于面状地物的"
  "特征点（界址点、拐角点）上逐点采集坐标，最后按坐标解析法计算面积。")

H2("（二）原理与方法")
P("1. 假定坐标系与设站")
P("在测区内任选一点作为测站，假定其坐标（如 X=1000.000 m，Y=1000.000 m，"
  "H=10.000 m），任选一个方向作为起始方向（后视方向），"
  "假定其方位角（如 0°00′00″），这样建立的独立坐标系称为假定坐标系。"
  "由于面积计算只与点间的相对位置有关，假定坐标系的平移、旋转不影响面积结果。")
P("2. 碎部点采集")
P("在测站上整平仪器，照准后视方向并置零（或输入假定方位角），然后依次"
  "照准立于各特征点的棱镜，测量水平角、竖直角和斜距，仪器自动计算出"
  "各点的三维坐标并记录。对同一个点应独立观测两次取平均，"
  "并检查两次坐标较差不大于限值。")
P("3. 面积计算——坐标解析法（鞋带公式）")
P("设多边形各顶点按顺时针（或逆时针）顺序编号为 1,2,…,n，坐标为 (Xi, Yi)，"
  "则面积")
p = doc.add_paragraph()
p.alignment = WD_ALIGN_PARAGRAPH.CENTER
run_cn(p.add_run("S = 1/2 · | Σ (Xi·Yi+1 − Xi+1·Yi) |   （i=1…n，Xn+1=X1，Yn+1=Y1）"),
       12, True)
P("该式即测量中常用的“坐标解析法”求面积公式，其特点是：计算结果与坐标"
  "原点和坐标轴方向无关，只取决于多边形顶点的相对位置；只要点的坐标精度"
  "相同，面积精度就与图形形状无关。计算时顶点必须按同一方向（顺时针或"
  "逆时针）依次排列，不能交叉、跳点，否则结果错误。")
P("作为检核，可同时计算各边边长和周长，并检查首末点是否闭合；"
  "面积中误差可按下式估算：")
p = doc.add_paragraph()
p.alignment = WD_ALIGN_PARAGRAPH.CENTER
run_cn(p.add_run("mS = (mP/2) · √[ Σ ( (Yi+1 − Yi−1)² + (Xi+1 − Xi−1)² ) ]"),
       12, True)
P("式中 mP 为点位中误差（一般取全站仪标称精度与作业条件综合取值，"
  "如 ±5 mm～±10 mm）。据此可判断面积成果的可靠性，并给出面积结果的"
  "中误差与相对精度。")

H2("（三）作业步骤")
ITEM("① 踏勘测区，选定测站位置，绘制测区草图并给各特征点编号；")
ITEM("② 架设全站仪，对中、整平，量取仪器高，假定测站坐标与起始方位角；")
ITEM("③ 照准后视方向置零，检查仪器参数（棱镜常数、温度气压改正等）；")
ITEM("④ 依次观测各特征点，记录点号、水平角、竖直角、斜距及算得的坐标；")
ITEM("⑤ 对边长较长或关键的点进行重复观测检核；")
ITEM("⑥ 检查各点是否闭合、有无明显粗差，绘制测点略图；")
ITEM("⑦ 用坐标解析法计算面积，估算面积中误差，填写面积测量成果表。")

H2("（四）精度分析与注意事项")
P("面积测量的精度主要取决于碎部点的点位精度、点位分布（图形越大、"
  "点间距越大，同样的点位误差对面积的影响越小）以及是否漏测、错测。"
  "注意事项：棱镜杆应竖直（圆气泡居中）；每个特征点应立在明显的拐角处；"
  "测站应选在能够通视全部特征点的位置，避免长边和过小的夹角；"
  "观测时注意棱镜常数设置（−30 mm 或 0）与现场一致；"
  "对同一测站不能通视的点，应搬站并以已测点作为已知点重新设站，"
  "保证前后测点在同一坐标系内。")

